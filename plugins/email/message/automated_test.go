func TestClassify(t *testing.T) {
	t.Parallel()

	for _, c := range classifyCases {
		t.Run(c.name, func(t *testing.T) {
			t.Parallel()

			if got := message.Classify(parseRaw(t, c.raw)); !reflect.DeepEqual(got, c.want) {
				t.Errorf("Classify() = %s, want %s", describe(got), describe(c.want))
			}
		})
	}
}

func TestClassifyFixtures(t *testing.T) {
	t.Parallel()

	cases := []struct {
		file string
		want message.Classification
	}{
		{"delivery-failure.eml", failedNobody},
		{"abuse-report.eml", message.Classification{Automation: message.AbuseReport}},
		{"read-receipt.eml", message.Classification{Automation: message.ReadReceipt}},
		{"auto-reply.eml", message.Classification{Automation: message.AutoReply, BulkHint: true}},
		{"list-mail.eml", message.Classification{Automation: message.ListMail}},
		{"gmail-reply.eml", message.Classification{}},
	}

	for _, c := range cases {
		t.Run(c.file, func(t *testing.T) {
			t.Parallel()

			if got := message.Classify(parseFixture(t, c.file)); !reflect.DeepEqual(got, c.want) {
				t.Errorf("Classify(%s) = %s, want %s", c.file, describe(got), describe(c.want))
			}
		})
	}
}

func TestClassifyFindsNothingInAMessageParseDidNotBuild(t *testing.T) {
	t.Parallel()

	if got := message.Classify(&message.Message{}); !reflect.DeepEqual(got, message.Classification{}) {
		t.Errorf("Classify() of a zero message = %s, want nothing", describe(got))
	}
}

// plainMail answers a raw text message holding the header fields given.
func plainMail(fields ...string) string {
	return strings.Join(append(fields, "Content-Type: text/plain"), "\r\n") + "\r\n\r\nA short note.\r\n"
}

// reportMail answers a raw report of reportType whose second part has partType and holds body.
func reportMail(reportType, partType, body string) string {
	return "Content-Type: multipart/report; report-type=" + reportType + "; boundary=\"report\"\r\n\r\n" +
		"--report\r\nContent-Type: text/plain\r\n\r\nA report on earlier mail.\r\n" +
		"--report\r\nContent-Type: " + partType + "\r\n\r\n" + body + "\r\n--report--\r\n"
}

// parseRaw answers raw parsed under testLimits.
func parseRaw(t *testing.T, raw string) *message.Message {
	t.Helper()
	m, err := message.Parse(strings.NewReader(raw), testLimits)
	if err != nil {
		t.Fatalf("Parse() error = %v, want nil", err)
	}
	return m
}

// describe answers c with its delivery report spelled out.
func describe(c message.Classification) string {
	return fmt.Sprintf("%+v with report %+v", c, c.Report)
}
