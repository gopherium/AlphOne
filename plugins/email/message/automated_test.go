// delayedStatus is the body of a delivery report that is still trying one recipient.
const delayedStatus = "Reporting-MTA: dns; mail.example.com\r\n\r\n" +
	"Final-Recipient: rfc822; nobody@example.com\r\nAction: delayed\r\nStatus: 4.4.7\r\n"

// failedStatus is the body of a delivery report that gave up on one recipient.
const failedStatus = "Reporting-MTA: dns; mail.example.com\r\n\r\n" +
	"Final-Recipient: rfc822; nobody@example.com\r\nAction: failed\r\nStatus: 5.1.1\r\n"

// failedNobody is the classification of a bounce for nobody@example.com.
var failedNobody = message.Classification{
	Automation: message.Bounce,
	Report: &message.DeliveryReport{
		Failed: []message.FailedRecipient{{Email: "nobody@example.com", Status: "5.1.1"}},
	},
}

